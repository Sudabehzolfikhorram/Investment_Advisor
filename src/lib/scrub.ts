// داده‌های فعلی نمونه‌اند و بعداً با داده واقعی جایگزین می‌شوند؛ به خواست طراح، اشاره به «فرضی» یا «آموزشی» بودن
// داده در طراحی نمایش داده نمی‌شود. این تابع فقط همین عبارت‌ها را برمی‌دارد و بقیه متن را دست نمی‌زند.
const sentences: [RegExp, string][] = [
  [/این صفحه نمونه طراحی است\. تمام[^.]*?فرضی‌اند؛[^.]*\.?/g, ""],
  [/طرح، ارقام و وضعیت‌های این پنجره صرفاً فرضی‌اند و هیچ مجوز یا فراخوان واقعی را تأیید نمی‌کنند\.?/g, ""],
  [/تمام آگهی‌ها، قیمت‌ها و موقعیت‌های این نمونه فرضی‌اند\.?/g, ""],
  [/تمام مبالغ و دوره‌ها آموزشی و فرضی‌اند\.\s*/g, ""],
  [/خلاصه فرضی و آموزشی؛ درخواست واقعی ثبت نشده است\.\s*/g, ""],
  [/(?:مبلغ ورود صرفاً فرضی است\.|تمام اطلاعات این مورد فرضی است؛|این نمونه فرضی است؛|مقایسه داده‌های فرضی است؛)\s*/g, ""],
  [/(?:آگهی‌ها و مبالغ|ارقام و سطح ریسک|تمام فرصت‌ها و ارقام|این گزینه و تمام ارقام و وضعیت‌های آن) فرضی‌اند؛\s*/g, ""],
  [/[؛،]\s*پروژه و پاسخ‌گو فرضی هستند/g, ""],
  [/سناریوی محاسبه صرفاً فرضی است/g, "سناریوی محاسبه نمونه است"],
  [/فقط سناریوی فرضی/g, "سناریوی نمونه"],
  [/سناریوی آموزشیِ?/g, "سناریوی نمونه"],
  [/داده آموزشی همین HTML؛\s*/g, ""],
  [/در این نمونه اتصال زنده نداریم؛\s*/g, ""],
  [/\s*هیچ نام، نرخ یا تضمین واقعی در این نمونه تأیید نشده است\.?/g, ""],
  [/\s*[—–-]\s*نمونه آموزشی/g, ""],
  [/([۰-۹0-9]+) سناریوی فرضی/g, "$1 گزینه"],
  [/تمام مشخصات و قیمت‌ها فرضی‌اند\.?/g, ""],
  [/همه فرصت‌ها فرضی‌اند\.?/g, ""],
  [/پیش‌نمایش تعاملی\s*[•·]\s*داده‌های فرضی/g, "پیش‌نمایش تعاملی"],
  [/پرونده آموزشی و کاملاً فرضی[؛،][^.]*\.?/g, ""],
  [/نمونه و ترتیبات آن فرضی‌اند[؛،]\s*/g, ""],
  [/پاسخ‌های فرضی/g, "پاسخ‌های پیشنهادی"],
  [/(?:بازده و زمان پرداخت )?صرفاً در سناریوی فرضی[؛،]\s*/g, ""],
  [/(?:صندوق|طرح جمعی|طرح|پروژه) فرضی[؛،]\s*/g, ""],
  [/نمونه (?:فرضی|آموزشی)[؛،:]\s*/g, ""],
  [/نمونه آموزشی\s*/g, ""],
  [/داده آموزشی[؛،]\s*/g, ""],
  [/[؛،]\s*(?:اطلاعات|داده‌های|ارقام) فرضی/g, ""],
  [/\s*[—–-]\s*(?:نمونه|شخصیت|سناریوی)\s+فرضی/g, ""],
  [/\s*[—–-]\s*فرضی\b/g, ""],
  [/[،,]?\s*(?:در )?(?:این )?(?:سناریوی|نمونه) فرضی/g, ""],
  [/نمونه فرضی\s*/g, ""],
  [/مقدار فرضی و /g, ""], [/تعداد فرضی و /g, ""],
  [/\s+فرضی(?:‌اند)?(?=[\s.،؛:)»]|$)/g, ""],
  [/مشخصات و شرایط واقعی/g, "مشخصات و شرایط"],
  [/همه فرصت‌ها نمونه‌اند؛[^.]*\.\s*/g, ""],
  [/رکورد آموزشی/g, "رکورد"],
  // برچسب دکمه‌های دریافت: قالب فایل (HTML) و فلش متنی نوشته نمی‌شود
  [/دریافت گزارش و چک‌لیست HTML\s*↓?/g, "دریافت گزارش"],
  [/(دریافت [^\n.،؛]{1,30}?)\s*HTML\s*↓?/g, "$1"],
  [/مثال آموزشی/g, "مثال"],
  [/الگوی آموزشی/g, "الگو"],
];
export function scrub(s: string): string {
  if (!/فرضی|آموزشی|این نمونه|HTML/.test(s)) return s;
  let out = s;
  for (const [re, to] of sentences) out = out.replace(re, to);
  return out.replace(/\s{2,}/g, " ").replace(/^[\s؛،:—–-]+|[\s؛،:—–-]+$/g, "").replace(/([؛،])\s*\1/g, "$1").replace(/«\s+/g, "«").replace(/\s+»/g, "»");
}
/** همه رشته‌های یک شیء داده را در جا پاک‌سازی می‌کند */
export function scrubDeep<T>(v: T): T {
  if (Array.isArray(v)) { v.forEach((x, i) => { if (typeof x === "string") v[i] = scrub(x); else scrubDeep(x); }); }
  else if (v && typeof v === "object") for (const k of Object.keys(v)) { const x = (v as Record<string, unknown>)[k]; if (typeof x === "string") (v as Record<string, unknown>)[k] = scrub(x); else scrubDeep(x); }
  return v;
}
